#!/usr/bin/env node
/* Mint test/dcmap-parity-vector.json — the ONE committed answer both U5 calculator paths must
   reproduce for one fixed set of inputs (U5 deliverable 4: "for the same inputs, the browser
   calculator path and the MCP path produce the same DTO — same profile hash, same bands, same
   receipts").

   Minted from the shared economics layer itself, so neither consumer is the authority:
     mcp-server/test/dcmap-contract.test.mjs        asserts the MCP tool reproduces it
     dc-map/site/test/calculator-parity.test.ts     asserts the browser calculator reproduces it
   If those two ever disagree, at least one of them fails against this file rather than both
   quietly agreeing about a different object.

   The vector is engine-coupled ON PURPOSE: it carries the engine revision and the modeled band, so
   a move in site/engine.js fails both suites loudly instead of silently re-baselining a published
   number. Re-mint deliberately, and say why in the commit:

     node mcp-server/scripts/mint-dcmap-parity-vector.mjs
*/
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  PARITY_VECTOR_PATH, buildSyntheticRelease, ineligibleBundle, materializeRelease, overlappingBundle,
  parityProjection, replacementBundle, scenarioBundle,
} from "../test/dcmap-scenario-fixture.mjs";

const HERE = fileURLToPath(new URL(".", import.meta.url));
const MCP = resolve(HERE, "..");
const dir = resolve(MCP, ".dcmap-test-releases", "mint");

const built = materializeRelease(dir, buildSyntheticRelease());
process.env.DCMAP_RELEASES = dir;

const { loadRelease } = await import(resolve(MCP, "dist/dcmap/economics-node/loader.js"));
const { priceTokenHere, compareScenarios } = await import(resolve(MCP, "dist/dcmap/economics/scenario.js"));
const { economicsContext } = await import(resolve(MCP, "dist/dcmap/layer.js"));

const opened = await loadRelease(dir);
if (!opened.ok) throw new Error(`could not open the synthetic release: ${opened.reasons.join("; ")}`);
const context = economicsContext();

const priced = await priceTokenHere(opened.release, scenarioBundle(built.release_id), context);
if (priced.status !== "modeled") throw new Error(`the parity scenario no longer prices: ${priced.missing.join("; ")}`);

/* The ranking request every U5 ambiguity claim is measured against: one point band, one disjoint
   band, one that straddles the first (so the answer is a connected group, not an order), and one
   whose accelerator differs from the fixed profile (so the answer is an exclusion with a reason). */
const rankingRequest = (sort) => ({
  comparison: scenarioBundle(built.release_id).comparison,
  scenarios: [scenarioBundle(built.release_id), replacementBundle(built.release_id),
    overlappingBundle(built.release_id), ineligibleBundle(built.release_id)],
  sort,
});
const project = (ranked) => ({
  status: ranked.status, sentence: ranked.sentence, profile_hash: ranked.profile_hash,
  metric_definition: ranked.metric_definition, ordering_basis: ranked.ordering_basis,
  groups: ranked.groups, excluded: ranked.excluded,
  eligible_ids: ranked.eligible.map((r) => r.scenario_id),
  eligible_bands: ranked.eligible.map((r) => r.value.band),
});
const ranked = project(await compareScenarios(opened.release, rankingRequest("overlap-groups"), context));
const rankedMidpoint = project(await compareScenarios(opened.release, rankingRequest("midpoint"), context));
if (!ranked.groups.some((g) => g.scenario_ids.length > 1))
  throw new Error("the ranking vector no longer exercises an overlap group of more than one scenario");
if (!ranked.excluded.length) throw new Error("the ranking vector no longer exercises an excluded scenario");

const vector = {
  note: "GENERATED by mcp-server/scripts/mint-dcmap-parity-vector.mjs. Synthetic inputs only — no "
    + "real-world site, tariff, contract or price is asserted. Both U5 calculator paths must reproduce it.",
  release_id: built.release_id,
  profile_hash: priced.profile_hash,
  priced: parityProjection(priced),
  ranked,
  ranked_midpoint: rankedMidpoint,
};
writeFileSync(PARITY_VECTOR_PATH, JSON.stringify(vector, null, 2) + "\n");
console.log(`minted parity vector for ${vector.release_id} (profile ${vector.profile_hash}) → ${PARITY_VECTOR_PATH}`);
