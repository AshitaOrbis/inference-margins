#!/usr/bin/env node
/* Vendor the U3 economics layer into src/dcmap/economics/ — VERBATIM, generated, never edited.

   `dc-map/economics/` is a separate pnpm package whose published entry is `dist/src/index.js`.
   This server is an npm package compiled by one `tsc -p tsconfig.json` with `rootDir: "src"`, so a
   relative import of those sources would drag them into the program and move `rootDir` to the
   repository root — `dist/stdio.js`, the `bin` entry, would become `dist/mcp-server/src/stdio.js`.
   Importing the built `dist/` instead would couple `npm test` to a pnpm build of another package.

   So the sources are COPIED, the same way mcp-server/worker/scripts/build.mjs already copies this
   package's own sources into worker/src/gen: one source of truth, a disposable copy beside the
   consumer, and a build that regenerates it every time so the copy cannot drift. The copy is
   byte-identical (asserted below by digest), git-ignored, and read-only by convention — U5 never
   edits dc-map/economics, and it never edits this copy either.

   The same copy is what the Worker bundles: worker/scripts/build.mjs copies this directory into
   src/gen/dcmap/economics, so both transports run the same U3 bytes. */
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const MCP = path.resolve(HERE, "..");
export const ECONOMICS = path.resolve(MCP, "..", "dc-map", "economics");
export const VENDORED = path.join(MCP, "src", "dcmap", "economics");
/* The Node-only filesystem loader lives OUTSIDE the runtime-agnostic copy on purpose: the Worker
   build copies src/dcmap/economics wholesale, and a `node:fs/promises` import inside that tree
   would be bundled into a runtime that has no filesystem. */
export const VENDORED_NODE = path.join(MCP, "src", "dcmap", "economics-node");

const sha256 = (bytes) => "sha256:" + createHash("sha256").update(bytes).digest("hex");

/** Copy dc-map/economics/src verbatim and return the per-file digests of what was written. */
export function syncEconomics({ target = VENDORED, nodeTarget = VENDORED_NODE, source = ECONOMICS } = {}) {
  const runtime = path.join(source, "src");
  const names = readdirSync(runtime).filter((f) => f.endsWith(".ts")).sort();
  if (names.length < 8) throw new Error(`economics source looks truncated: ${names.length} modules`);
  rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  const digests = {};
  for (const name of names) {
    const from = path.join(runtime, name);
    cpSync(from, path.join(target, name));
    const before = readFileSync(from);
    const after = readFileSync(path.join(target, name));
    if (!before.equals(after)) throw new Error(`vendored copy of ${name} is not byte-identical`);
    digests[name] = sha256(after);
  }
  writeFileSync(path.join(target, "VENDORED.json"), JSON.stringify({
    note: "GENERATED by mcp-server/scripts/sync-economics.mjs from dc-map/economics/src — DO NOT EDIT.",
    source: "dc-map/economics/src",
    modules: digests,
  }, null, 2) + "\n");

  /* The loader is the ONE file that is not copied byte-for-byte: it sits one directory deeper
     here than it does in the package, so its single relative import of the release module is
     re-pointed. Nothing else is rewritten, and the rewrite is asserted to have happened. */
  const loaderPath = path.join(source, "node", "loader.ts");
  const loader = readFileSync(loaderPath, "utf8");
  const rewritten = loader.replaceAll("'../src/", "'../economics/");
  if (rewritten === loader) throw new Error("economics node loader no longer imports from '../src/'");
  rmSync(nodeTarget, { recursive: true, force: true });
  mkdirSync(nodeTarget, { recursive: true });
  writeFileSync(path.join(nodeTarget, "loader.ts"),
    "/* GENERATED by mcp-server/scripts/sync-economics.mjs from dc-map/economics/node/loader.ts — DO NOT EDIT.\n" +
    "   Verbatim apart from the relative path of the release module, which moved one level. */\n" + rewritten);
  digests["node/loader.ts"] = sha256(Buffer.from(loader, "utf8"));
  return digests;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const digests = syncEconomics();
  console.log(`sync-economics: vendored ${Object.keys(digests).length} U3 modules verbatim into src/dcmap/economics`);
}
