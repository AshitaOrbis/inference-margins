// build-astra-pro-estimates.mjs — generate the "Astra Pro estimates" category from its registry
// (bq-3351). Authoring-time tool, part of `npm run build`; the deployed site stays build-free.
//
//   node scripts/build-astra-pro-estimates.mjs          write the outputs
//   node scripts/build-astra-pro-estimates.mjs --check  exit 1 if any output is stale
//
// Inputs:  site/astra-pro-estimates.js (the recorded operating points and provenance)
//          research/astra-pro-estimates/answers/<key>.md (each run's answer, verbatim)
// Outputs: site/index.html, between the BEGIN/END astra-pro-cards markers (the card faces)
//          research/astra-pro-estimates/<key>-astra-pro.md (each model's review page source;
//            build-research-html.mjs renders it to site/research/<key>-astra-pro.html)
//          research/astra-pro-estimates/INDEX.json (the annex entries build-research-html reads)
//
// Every percentage written here comes from astraProReplay() — the engine's result on a recorded
// operating point. Nothing numeric is typed into the page by hand, and the --check mode (run by
// tests/astra-pro-estimates.test.mjs) fails when an engine change would move a face.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const E = require(join(ROOT, "site", "engine.js"));
const A = require(join(ROOT, "site", "astra-pro-estimates.js"));
const CHECK = process.argv.includes("--check");
const SRC = join(ROOT, "research", "astra-pro-estimates");
const BEGIN = "<!-- BEGIN astra-pro-cards (generated by scripts/build-astra-pro-estimates.mjs from site/astra-pro-estimates.js — do not edit by hand) -->";
const END = "<!-- END astra-pro-cards -->";

const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const pct = v => Math.round(v) + "%";
const one = v => Number(v).toFixed(1);
/* model-authored card lines: escaped, then Markdown code spans rendered as <code> (F11a) */
const lineHtml = s => esc(s).replace(/`([^`]+)`/g, "<code>$1</code>");
const sha = s => createHash("sha256").update(s).digest("hex");
const hwName = k => (E.HW[k] && E.HW[k].name) || k;

function fleetText(ov) {
  return Object.entries(ov.blend || {}).filter(([, w]) => w > 0)
    .map(([k, w]) => `${hwName(k)} ${w}% at $${Number(ov.rentAbsLeg && ov.rentAbsLeg[k]).toFixed(2)}/h`).join(" · ");
}
function carrierText(rec) {
  if (rec.carrier === "custom") return `the calculator's blank <code>custom</code> row on the <code>${esc(rec.scenarios.central.overrides.customDonor || "dsr1")}</code> attention geometry (a declared approximation — this model's architecture is ${rec.open ? "published but matches no stated row" : "not published"})`;
  const m = E.MODELS.find(x => x.id === rec.carrier);
  return `the stated geometry of the site's <code>${esc(rec.carrier)}</code> row (${esc(m ? m.name : rec.carrier)}), with every magnitude, price, fleet and traffic input from this run`;
}

function readings(rec) {
  const r = A.astraProReadings(rec, E);
  const ref = A.astraProReplay({ ...rec, scenarios: { central: { overrides: { ...rec.scenarios.central.overrides,
    ...("billCacheHit" in rec.scenarios.central.overrides ? { billCacheHit: 60 } : {}) },
    traffic: { mode: "custom", io_ratio: 15, cache_hit: 60 } } } }, "central", E).margin * 100;
  for (const k of A.ASTRA_PRO_SCENARIOS)
    if (!isFinite(r[k])) throw new Error(`${rec.key}/${k}: the engine returned no finite margin`);
  if (r.central < 0 && !rec.withheld)
    throw new Error(`${rec.key}: central replay ${r.central.toFixed(2)}% is negative — the owner's rule treats that as an input error; record it as withheld or re-derive`);
  return { ...r, reference: ref };
}

function card(rec, r) {
  const c = rec.scenarios.central, t = c.traffic, ov = c.overrides;
  const st = rec.stated || {};
  const token = A.astraProShareToken(rec, E);
  /* The run's heading-0 line 1 restates its own stated figure, which the provenance line already prints
     (to one decimal); the face quotes line 2 — the input the run says decides the number. Both lines
     stay verbatim in the answer on the review page. */
  if (!Array.isArray(rec.card_lines) || rec.card_lines.length !== 2 || !/at list/i.test(rec.card_lines[0]))
    throw new Error(`${rec.key}: heading 0 must parse to two lines, the first the stated reading "… at list …" (got ${JSON.stringify(rec.card_lines)})`);
  const lines = rec.card_lines.slice(1, 2).map(lineHtml).join("<br>");
  return `  <details class="prov ape-card" id="ape-${rec.key}" data-ape-key="${rec.key}">
    <summary><strong>${esc(rec.provider)} — ${esc(rec.name)}</strong> <span class="prov-margin">serving margin <span class="ape-mid">~${pct(r.central)}</span> <span class="prov-ci">(this calculator on Astra Pro's central inputs, at list price; its low- and high-margin scenarios: <span class="ape-span">${pct(r.low_margin)}–${pct(r.high_margin)}</span>)</span></span></summary>
    <div class="prov-body">
      <p class="ape-prov"><strong>Estimated by GPT-6 Astra Pro</strong>, ${esc(rec.dive.date)}, research run <code>${esc(rec.dive.id)}</code>. Its own stated reading: ${one(st.headline_pct)}% (${one(st.low_pct)}–${one(st.high_pct)}%).</p>
      ${lines ? `<p class="ape-lines"><strong>What decides it, in its own words:</strong> ${lines}</p>` : ""}
      <p class="cardmeta"><strong>Metric:</strong> blended serving margin at list price (${esc(String(rec.api_model).split(";")[0])}) · <strong>traffic:</strong> ${t.io_ratio}:1 input:output, ${t.cache_hit}% cache hits · <strong>fleet:</strong> ${fleetText(ov)} · <strong>utilization:</strong> ${ov.util}% · <strong>model:</strong> ${ov.active}B active / ${ov.total}B total, ${esc(ov.precision)}. <em>Its own operating point — not cross-model comparable.</em> At the page's Reference traffic (15:1, 60% cache) and list price, the same inputs compute ~${pct(r.reference)}.</p>
      <p class="cardmeta"><strong>Carrier:</strong> ${carrierText(rec)}.</p>
      <p class="load-op-row"><span class="load-op-lead">Reach this operating point in the calculator:</span> <a class="ape-reproduce" href="?s=${encodeURIComponent(token)}" aria-label="Reproduce the ${esc(rec.name)} card in the calculator">Reproduce this card ↑ (Astra Pro's central inputs)</a></p>
      <p><a class="ape-review" href="${esc(rec.review_page)}" aria-label="Full GPT-6 Astra Pro review of ${esc(rec.name)}">Full GPT-6 Astra Pro review →</a></p>
    </div>
  </details>`;
}

function inputsTable(rec) {
  const keys = [];
  for (const k of A.ASTRA_PRO_SCENARIOS) for (const f of Object.keys(rec.scenarios[k].overrides)) if (!keys.includes(f)) keys.push(f);
  const cell = (k, f) => { const v = rec.scenarios[k].overrides[f]; return v === undefined ? "—" : (typeof v === "object" ? "`" + JSON.stringify(v) + "`" : String(v)); };
  const rows = keys.map(f => `| \`${f}\` | ${cell("central", f)} | ${cell("low_margin", f)} | ${cell("high_margin", f)} |`);
  const tr = k => `${rec.scenarios[k].traffic.io_ratio}:1, ${rec.scenarios[k].traffic.cache_hit}% cache`;
  rows.push(`| traffic | ${tr("central")} | ${tr("low_margin")} | ${tr("high_margin")} |`);
  return "| input | central | low-margin scenario | high-margin scenario |\n|---|---|---|---|\n" + rows.join("\n");
}

/* Two rendering-only transforms of the verbatim answer, stated on the page: display math
   (\[ … \]) is set as a preformatted block so the Markdown renderer cannot read "[x](0.64)" inside
   an equation as a link, and links into ChatGPT's own sandbox (files no reader can open) are
   shown as their text. The stored answer, and its hash, are untouched. */
function presentAnswer(answer) {
  return answer
    .replace(/^\\\[\s*\n([\s\S]*?)\n\s*\\\]\s*$/gm, (_, body) => "```text\n" + body.trim() + "\n```")
    .replace(/\\\[([^\n]*?)\\\]/g, (_, body) => "`" + body.trim() + "`")
    .replace(/\\\(([^\n]*?)\\\)/g, (_, body) => "`" + body.trim() + "`")
    .replace(/\[([^\]]*)\]\(sandbox:[^)]*\)/g, "$1 (a file in the research run's own workspace, not published)");
}

/* F6 (review r1): an engine-derived figure a reading cites is written as {{REF}} and filled here from
   the replay, so a reading cannot go stale when the engine moves. */
function readingText(rec, r) {
  const d = r.reference - r.central;
  const rel = Math.abs(d) < 1.5 ? "close to" : d > 0 ? "above" : "below";
  const out = String(rec.reading || "").replace(/\{\{REF\}\}/g, "~" + pct(r.reference)).replace(/\{\{REFREL\}\}/g, rel);
  if (/\{\{|\}\}/.test(out)) throw new Error(`${rec.key}: unknown template token in reading`);
  return out;
}

function reviewPage(rec, r, answer) {
  const st = rec.stated || {};
  return `# ${rec.name} — GPT-6 Astra Pro estimate (${rec.dive.date})

**Provenance.** One GPT-6 Astra Pro research run (ChatGPT, model \`${rec.dive.model_slug}\`), request \`${rec.dive.id}\`, answered ${rec.dive.answered_at}. It was given this calculator's input contract, the Claude Opus 4.x reference estimate and the live connector's scenario space, and asked to set every input for ${rec.name} from public evidence. The answer is reproduced below verbatim except for three presentation changes: ChatGPT's interface citation markers are removed, as on every page of this annex; links into the research run's own sandbox (files no reader can open) keep their text and lose the dead target; and equations are set as preformatted text, with a space between a bracket and a parenthesis inside them so the renderer does not read a product as a link; its sources are cited by URL in the text (published text SHA-256 \`${rec.dive.answer_sha256}\`; as received, \`${rec.dive.raw_answer_sha256}\`).

## What the site shows

| reading | value |
|---|---|
| **Card headline** — this calculator on the run's central inputs, at list | **~${pct(r.central)}** (${r.central.toFixed(2)}%) |
| Span — the run's own low- and high-margin scenarios, same engine | ${pct(r.low_margin)}–${pct(r.high_margin)} (${r.low_margin.toFixed(2)}% – ${r.high_margin.toFixed(2)}%) |
| The run's own stated reading | ${one(st.headline_pct)}% (${one(st.low_pct)}–${one(st.high_pct)}%) |
| Same central inputs at the page's Reference traffic (15:1, 60% cache) — context, not the headline | ~${pct(r.reference)} |

The span is the author's judgment span: two scenarios it called plausible as a whole, not a probability interval and not a bound. The headline is a modeled unit direct-serving margin from public information; it is not a disclosure by the provider and not a company gross margin.

## Our reading

${readingText(rec, r)}

## The operating point

Carrier: ${carrierText(rec).replace(/<\/?code>/g, "`")}. \`batchShare\` and \`discount\` are 0 in every run (list basis).

${inputsTable(rec)}

## The answer, verbatim

${presentAnswer(answer)}
`;
}

const recs = A.ASTRA_PRO_REGISTRY.estimates;
const keys = new Set();
const outputs = [];
const index = [];
const cards = [];
for (const rec of recs) {
  if (keys.has(rec.key)) throw new Error(`duplicate key ${rec.key}`);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(rec.key)) throw new Error(`key ${JSON.stringify(rec.key)} must be lower-case id characters`);
  keys.add(rec.key);
  if (rec.review_page !== `research/${rec.key}-astra-pro.html`) throw new Error(`${rec.key}: review_page must be research/${rec.key}-astra-pro.html`);
  const ansPath = join(SRC, "answers", `${rec.key}.md`);
  if (!existsSync(ansPath)) throw new Error(`${rec.key}: no answer at research/astra-pro-estimates/answers/${rec.key}.md`);
  const answer = readFileSync(ansPath, "utf8");
  if (sha(answer) !== rec.dive.answer_sha256) throw new Error(`${rec.key}: answer sha256 ${sha(answer)} != registry ${rec.dive.answer_sha256}`);
  const r = readings(rec);
  cards.push(card(rec, r));
  outputs.push([join(SRC, `${rec.key}-astra-pro.md`), reviewPage(rec, r, answer)]);
  index.push({ md: `research/astra-pro-estimates/${rec.key}-astra-pro.md`, slug: `${rec.key}-astra-pro`,
    title: `${rec.name} — GPT-6 Astra Pro estimate`,
    desc: `One GPT-6 Astra Pro research run (${rec.dive.date}) setting every calculator input for ${rec.name} from public evidence; the site's card is this calculator's result on those inputs (~${pct(r.central)} at list, span ${pct(r.low_margin)}–${pct(r.high_margin)}).` });
}
outputs.push([join(SRC, "INDEX.json"), JSON.stringify(index, null, 1) + "\n"]);

const idxPath = join(ROOT, "site", "index.html");
const html = readFileSync(idxPath, "utf8");
const a = html.indexOf(BEGIN), b = html.indexOf(END);
if (a < 0 || b < a || html.indexOf(BEGIN, a + 1) >= 0) throw new Error("site/index.html: expected exactly one BEGIN…END astra-pro-cards block");
outputs.push([idxPath, html.slice(0, a + BEGIN.length) + "\n" + cards.join("\n\n") + (cards.length ? "\n" : "") + "  " + html.slice(b)]);

let stale = 0;
for (const [p, body] of outputs) {
  const cur = existsSync(p) ? readFileSync(p, "utf8") : null;
  if (cur === body) continue;
  stale++;
  if (CHECK) { console.error(`STALE: ${p.slice(ROOT.length + 1)}`); continue; }
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, body);
  console.log(`built: ${p.slice(ROOT.length + 1)}`);
}
if (CHECK && stale) { console.error(`${stale} Astra Pro estimate output(s) stale — run node scripts/build-astra-pro-estimates.mjs`); process.exit(1); }
console.log(`astra-pro estimates: ${recs.length} record(s), ${stale} output(s) ${CHECK ? "stale" : "written"}`);
